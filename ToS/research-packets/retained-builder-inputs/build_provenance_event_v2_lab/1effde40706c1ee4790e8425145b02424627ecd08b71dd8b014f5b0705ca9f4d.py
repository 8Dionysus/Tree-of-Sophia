def _sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _sha256(path: Path) -> str:
    return _sha256_bytes(path.read_bytes())


def _write_json(path: Path, payload: dict[str, Any]) -> None:
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def _iso_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="microseconds")


def _canonical_argv_sha256(argv: list[str]) -> str:
    payload = json.dumps(
        argv,
        ensure_ascii=False,
        separators=(",", ":"),
    ).encode("utf-8")
    return _sha256_bytes(payload)


def _repo_path(ref: str) -> Path:
    return REPO_ROOT / ref


def _binding(ref: str) -> dict[str, str]:
    return {"ref": ref, "sha256": _sha256(_repo_path(ref))}


def _prepare_environment() -> int:
    executable = Path(sys.executable).resolve()
    payload = {
        "schema_version": "tos_provenance_environment_profile_v1",
        "profile_id": "tos.environment.provenance-event-v2.synthetic-abc",
        "captured_at": _iso_now(),
        "runtime": {
            "implementation": platform.python_implementation(),
            "version": platform.python_version(),
            "executable_sha256": _sha256(executable),
            "unicode_version": unicodedata.unidata_version,
        },
        "platform": {
            "system": platform.system(),
            "release": platform.release(),
            "machine": platform.machine(),
            "hardware_target": "cpu",
        },
        "capture_boundary": {
            "absolute_paths_recorded": False,
            "environment_variables_recorded": False,
            "packages_enumerated": False,
            "reason": "The lab uses only CPython standard-library byte and Unicode operations.",
        },
    }
    _write_json(_repo_path(ENVIRONMENT_REF), payload)
    print(f"prepared {ENVIRONMENT_REF}")
    return 0


def _entity(ref: str, role: str, verified_at: str) -> dict[str, Any]:
    path = _repo_path(ref)
    return {
        "entity_ref": ref,
        "role": role,
        "sha256": _sha256(path),
        "size_bytes": path.stat().st_size,
        "media_type": "text/plain; charset=utf-8",
        "availability": "tracked",
        "content_disclosure": "synthetic_public",
        "fixity_verified": True,
        "fixity_verified_at": verified_at,
    }


