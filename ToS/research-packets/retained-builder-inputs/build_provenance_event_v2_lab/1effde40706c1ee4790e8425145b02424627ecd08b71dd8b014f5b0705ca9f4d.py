def _run_variant(variant: str) -> int:
    environment_path = _repo_path(ENVIRONMENT_REF)
    if not environment_path.is_file():
        raise SystemExit("environment profile is absent; run --prepare first")

    argv = ["python", SCRIPT_REF, "--variant", variant]
    started_at = _iso_now()
    started_ns = time.perf_counter_ns()
    status = "completed"
    exit_code = 0
    terminal_reason: str | None = None
    output_ref: str | None = None
    byproduct_ref: str | None = None

    input_bytes = _repo_path(INPUT_FIXTURE_REF).read_bytes()
    if variant == "A":
        output_ref = OUTPUT_REFS[variant]
        _repo_path(output_ref).write_bytes(input_bytes)
    elif variant == "B":
        output_ref = OUTPUT_REFS[variant]
        source = input_bytes.decode("utf-8")
        _repo_path(output_ref).write_text(
            unicodedata.normalize("NFC", source),
            encoding="utf-8",
        )
    else:
        try:
            input_bytes.decode("utf-8").encode("ascii", errors="strict")
        except UnicodeEncodeError:
            status = "failed"
            exit_code = 7
            terminal_reason = "ascii_strict_rejected_non_ascii_input"
            byproduct_ref = BYPRODUCT_REFS[variant]
            _repo_path(byproduct_ref).write_bytes(FAILURE_BYTES)
        else:
            raise RuntimeError("negative control unexpectedly accepted the non-ASCII input fixture")

    duration_ms = round((time.perf_counter_ns() - started_ns) / 1_000_000, 6)
    ended_at = _iso_now()
    event = _event(
        variant=variant,
        argv=argv,
        started_at=started_at,
        ended_at=ended_at,
        duration_ms=duration_ms,
        status=status,
        exit_code=exit_code,
        terminal_reason=terminal_reason,
        output_ref=output_ref,
        byproduct_ref=byproduct_ref,
    )
    _write_json(_repo_path(EVENT_REFS[variant]), event)
    print(f"{variant}: status={status} exit_code={exit_code}")
    return exit_code


def _finalize() -> int:
    variants: list[dict[str, Any]] = []
    for variant in ("A", "B", "C"):
        event_ref = EVENT_REFS[variant]
        event = json.loads(_repo_path(event_ref).read_text(encoding="utf-8"))
        output_ref = OUTPUT_REFS.get(variant)
        byproduct_ref = BYPRODUCT_REFS.get(variant)
        variants.append(
            {
                "variant_id": variant,
                "operation": OPERATIONS[variant],
                "expected_status": EXPECTED_STATUS[variant],
                "expected_relation": EXPECTED_RELATION[variant],
                "expected_exit_code": 7 if variant == "C" else 0,
                "event_ref": event_ref,
                "event_sha256": _sha256(_repo_path(event_ref)),
                "input_ref": INPUT_FIXTURE_REF,
                "input_sha256": _sha256(_repo_path(INPUT_FIXTURE_REF)),
                "output_ref": output_ref,
                "output_sha256": _sha256(_repo_path(output_ref)) if output_ref else None,
                "byproduct_ref": byproduct_ref,
                "byproduct_sha256": (
                    _sha256(_repo_path(byproduct_ref)) if byproduct_ref else None
                ),
                "captured_command": event["method"]["command_capture"]["argv"],
            }
        )

    manifest = {
        "schema_version": "tos_provenance_event_v2_lab_v1",
        "lab_id": "tos.lab.provenance-event-v2.synthetic-abc",
        "contract": _binding(SCHEMA_REF),
        "plan": _binding(PLAN_REF),
        "builder": _binding(SCRIPT_REF),
        "environment_profile": _binding(ENVIRONMENT_REF),
        "input_fixture": _binding(INPUT_FIXTURE_REF),
        "authority_posture": "public_synthetic_mechanics_only",
        "authority_limits": {
            "private_source_used": False,
            "model_invoked": False,
            "human_evidence_created": False,
            "execution_truth_established": False,
            "content_truth_established": False,
            "rights_clearance_established": False,
            "semantic_claim_created": False,
            "canon_effect": False,
        },
        "variants": variants,
        "negative_controls": NEGATIVE_CONTROLS,
    }
    _write_json(_repo_path(MANIFEST_REF), manifest)
    print(f"finalized {MANIFEST_REF}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--prepare", action="store_true")
    group.add_argument("--variant", choices=("A", "B", "C"))
    group.add_argument("--finalize", action="store_true")
    args = parser.parse_args()
    if args.prepare:
        return _prepare_environment()
    if args.variant:
        return _run_variant(args.variant)
    return _finalize()


if __name__ == "__main__":
    raise SystemExit(main())
